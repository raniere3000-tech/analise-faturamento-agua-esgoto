def fmt_num(v, dec=0):
    try:
        if dec==0:
            return f"{v:,.0f}".replace(",", ".")
        s = f"{v:,.{dec}f}"
        return s.replace(",", "§").replace(".", ",").replace("§", ".")
    except:
        return("0")

def fmt_moeda_br(v):
    try:
        s = f"{v:,.2f}"
        return s.replace(",", "§").replace(".", ",").replace("§", ".")
    except:
        return "0,00"

def fmt_int_br(v):
    try:
        return f"{v:,.0f}".replace(",", ".")
    except:
        return "0"

