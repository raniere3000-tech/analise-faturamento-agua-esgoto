barra_progresso = tqdm(
    total=100,
    desc="Iniciando",
    unit="%",
    bar_format="{l_bar}{bar}| {n:.0f}%"
)

def atualiza_progresso(percentual, descricao):
    percentual = max(0, min(100, float(percentual)))
    barra_progresso.set_description_str(descricao)
    incremento = percentual - barra_progresso.n
    if incremento > 0:
        barra_progresso.update(incremento)

def progresso_da_etapa(indice, total, inicio, fim, descricao):
    if total <= 0:
        atualiza_progresso(fim, descricao)
        return
    percentual = inicio + (fim - inicio) * indice / total
    atualiza_progresso(percentual, descricao)

