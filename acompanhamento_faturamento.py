def processa_consumo(caminho):
    print(f"   ⚙️ Processando CONSUMO: {os.path.basename(caminho)}")
    df = le_dataframe(caminho)

    possiveis_nomes_ligacao = ["N. Ligacao", "N. da Ligacao", "N Ligacao", "N. da Ligação", "N. Ligação"]
    col_ligacao = next((c for c in possiveis_nomes_ligacao if c in df.columns), None)
    if col_ligacao is None:
        raise KeyError(
            f"Coluna de nº de ligação não encontrada no arquivo de CONSUMO "
            f"{os.path.basename(caminho)}. Colunas disponíveis: {list(df.columns)}"
        )

    for c in ["Leitura Atual", "Consumo Medido", "Consumo Faturado"] + col_economias:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0)

    df["Total Economias"] = df[col_economias].sum(axis=1)
    df["Qtd. Tipos de Economia"] = (df[col_economias] > 0).sum(axis=1)
    df["Economia Mista"] = df["Qtd. Tipos de Economia"].apply(lambda x: "Sim" if x > 1 else "Não")
    nome_arquivo = os.path.basename(caminho)
    match = re.search(r"(\d{2})[-/](\d{4})", nome_arquivo)
    df["Referência"] = f"{match.group(1)}/{match.group(2)}" if match else np.nan

    df["N. Ligação_consumo"] = df[col_ligacao].astype(str).str.strip()

    colunas_conflito = ["Grupo", "Situacao Ligacao", "Nome Cliente", "Categoria", col_ligacao]
    df = df.drop(columns=[c for c in colunas_conflito if c in df.columns], errors="ignore")

    return df.drop_duplicates(subset=["N. Ligação_consumo", "Referência"])

