def detecta_linha_cabecalho(caminho, sheet_name=0, max_linhas=10):
    ext = os.path.splitext(caminho)[1].lower()
    try:
        if ext in (".xlsx", ".xls"):
            df_raw = pd.read_excel(caminho, sheet_name=sheet_name, header=None,
                                    dtype=str, nrows=max_linhas)
        else:
            with open(caminho, "rb") as f_bytes:
                raw = f_bytes.read()
                try:
                    content = raw.decode("utf-8-sig")
                except UnicodeDecodeError:
                    content = raw.decode("latin-1")
            df_raw = pd.read_csv(io.StringIO(content), sep=";", header=None,
                                  dtype=str, nrows=max_linhas)
    except:
        return None
    todas_colunas_possiveis = COLUNAS_CONSUMO | COLUNAS_FATURA | COLUNAS_CRONOGRAMA
    for i in range(len(df_raw)):
        valores_linha = set(str(v).strip() for v in df_raw.iloc[i].tolist())
        if len(valores_linha & todas_colunas_possiveis) >= 2:
            return i
    return None

def le_dataframe(caminho, nrows=None, sheet_name=0):
    ext = os.path.splitext(caminho)[1].lower()
    linha_header = detecta_linha_cabecalho(caminho, sheet_name=sheet_name)
    if linha_header is None:
        linha_header = 0
    if ext == ".csv":
        with open(caminho, "rb") as f_bytes:
            raw = f_bytes.read()
            try:
                content = raw.decode("utf-8-sig")
            except:
                content = raw.decode("latin-1")
        f = io.StringIO(content)
        primeira_linha = f.readline()
        skip = linha_header
        if primeira_linha.strip().lower().startswith("sep="):
            skip += 1
        f.seek(0)
        df = pd.read_csv(f, sep=";", skiprows=skip, dtype=str)
    elif ext in (".xlsx", ".xls"):
        df = pd.read_excel(caminho, dtype=str, header=linha_header)
    else:
        return None
    df.columns = df.columns.astype(str).str.strip().str.replace('"', '').str.replace('ï»¿', '')
    df.columns = [c.replace("P?blica", "Publica").replace("Pública", "Publica") for c in df.columns]
    return df

def identifica_tipo(colunas):
    colunas = set(colunas)
    if COLUNAS_CONSUMO.issubset(colunas):
        return "consumo"
    if COLUNAS_FATURA.issubset(colunas):
        return "fatura"
    if COLUNAS_CRONOGRAMA.issubset(colunas):
        return "cronograma"
    return "desconhecido"

def padroniza_referencia(serie):
    serie = serie.astype(str).str.strip()
    dt_completa = pd.to_datetime(serie, format="%d/%m/%Y", errors="coerce")
    faltantes = dt_completa.isna()
    if faltantes.any():
        dt_mes = pd.to_datetime(serie[faltantes], format="%m/%Y", errors="coerce")
        dt_completa.loc[faltantes] = dt_mes
    return dt_completa.dt.strftime("%m/%Y")

